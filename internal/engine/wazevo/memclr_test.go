// A large zero memory.fill calls runtime.memclrNoHeapPointers, which relies on
// X15 being zero. Keeping 16 f64 values live across the fill makes the compiled
// code use every XMM register.
//
// The affected memclr loops only run without AVX2: use GODEBUG=cpu.avx2=off to
// reproduce on newer amd64 CPUs. See https://github.com/wazero/wazero/issues/2589
func TestMemoryFillZeroWithAllVectorRegistersLive(t *testing.T) {
	// $x, $n are the parameters. The locals are $i, $bad, $s and $v0..$v15.
	locals := []wasm.ValueType{i32, i32, f64}
	for range 16 {
		locals = append(locals, f64)
	}

	// run(x, n) fills [0, n) with 0xab, computes $v0..$v15 from x, fills [0, n)
	// with zero and returns the number of bytes that are not zero.
	module := &wasm.Module{
		TypeSection:     []wasm.FunctionType{{Params: []wasm.ValueType{f64, i32}, Results: []wasm.ValueType{i32}}},
		FunctionSection: []wasm.Index{0},
		MemorySection:   &wasm.Memory{Min: 1},
		ExportSection:   []wasm.Export{{Name: "run", Type: wasm.ExternTypeFunc, Index: 0}},
		CodeSection: []wasm.Code{{
			LocalTypes: locals,
			Body: []byte{
				0x41, 0x00, 0x41, 0xab, 0x01, 0x20, 0x01, 0xfc, 0x0b, 0x00, 0x20, 0x00, 0x44, 0x00, 0x00, 0x00,
				0x00, 0x00, 0x00, 0xf4, 0x3f, 0xa0, 0x21, 0x05, 0x20, 0x05, 0x44, 0x00, 0x00, 0x00, 0x00, 0x00,
				0x00, 0xf1, 0x3f, 0xa2, 0x21, 0x06, 0x20, 0x06, 0x44, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xf2,
				0x3f, 0xa2, 0x21, 0x07, 0x20, 0x07, 0x44, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xf3, 0x3f, 0xa2,
				0x21, 0x08, 0x20, 0x08, 0x44, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xf4, 0x3f, 0xa2, 0x21, 0x09,
				0x20, 0x09, 0x44, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xf5, 0x3f, 0xa2, 0x21, 0x0a, 0x20, 0x0a,
				0x44, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xf6, 0x3f, 0xa2, 0x21, 0x0b, 0x20, 0x0b, 0x44, 0x00,
				0x00, 0x00, 0x00, 0x00, 0x00, 0xf7, 0x3f, 0xa2, 0x21, 0x0c, 0x20, 0x0c, 0x44, 0x00, 0x00, 0x00,
				0x00, 0x00, 0x00, 0xf8, 0x3f, 0xa2, 0x21, 0x0d, 0x20, 0x0d, 0x44, 0x00, 0x00, 0x00, 0x00, 0x00,
				0x00, 0xf9, 0x3f, 0xa2, 0x21, 0x0e, 0x20, 0x0e, 0x44, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xfa,
				0x3f, 0xa2, 0x21, 0x0f, 0x20, 0x0f, 0x44, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xfb, 0x3f, 0xa2,
				0x21, 0x10, 0x20, 0x10, 0x44, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xfc, 0x3f, 0xa2, 0x21, 0x11,
				0x20, 0x11, 0x44, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xfd, 0x3f, 0xa2, 0x21, 0x12, 0x20, 0x12,
				0x44, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xfe, 0x3f, 0xa2, 0x21, 0x13, 0x20, 0x13, 0x44, 0x00,
				0x00, 0x00, 0x00, 0x00, 0x00, 0xff, 0x3f, 0xa2, 0x21, 0x14, 0x41, 0x00, 0x41, 0x00, 0x20, 0x01,
				0xfc, 0x0b, 0x00, 0x02, 0x40, 0x03, 0x40, 0x20, 0x02, 0x20, 0x01, 0x4f, 0x0d, 0x01, 0x20, 0x02,
				0x2d, 0x00, 0x00, 0x04, 0x40, 0x20, 0x03, 0x41, 0x01, 0x6a, 0x21, 0x03, 0x0b, 0x20, 0x02, 0x41,
				0x01, 0x6a, 0x21, 0x02, 0x0c, 0x00, 0x0b, 0x0b, 0x20, 0x05, 0x20, 0x06, 0xa0, 0x20, 0x07, 0xa0,
				0x20, 0x08, 0xa0, 0x20, 0x09, 0xa0, 0x20, 0x0a, 0xa0, 0x20, 0x0b, 0xa0, 0x20, 0x0c, 0xa0, 0x20,
				0x0d, 0xa0, 0x20, 0x0e, 0xa0, 0x20, 0x0f, 0xa0, 0x20, 0x10, 0xa0, 0x20, 0x11, 0xa0, 0x20, 0x12,
				0xa0, 0x20, 0x13, 0xa0, 0x20, 0x14, 0xa0, 0x21, 0x04, 0x20, 0x03, 0x20, 0x04, 0x20, 0x04, 0x62,
				0x6a, 0x0b,
			},
		}},
	}

	ctx := context.Background()
	r := wazero.NewRuntimeWithConfig(ctx, wazero.NewRuntimeConfigCompiler())
	defer func() { require.NoError(t, r.Close(ctx)) }()

	mod, err := r.Instantiate(ctx, binaryencoding.EncodeModule(module))
	require.NoError(t, err)

	for _, n := range []uint64{512, 1023, 1024, 1500, 2047, 2048, 4096, 8192} {
		res, err := mod.ExportedFunction("run").Call(ctx, math.Float64bits(1.5), n)
		require.NoError(t, err)
		// The result is an i32: only the low 32 bits are meaningful.
		require.Equal(t, uint32(0), uint32(res[0]), "non-zero bytes after zero fill of %d bytes", n)
	}
}
